    synonyms: tuple[str, ...]  # normalized phrases that map a query to this occasion
    name_terms: tuple[str, ...]  # words that, inside a product title, signal this occasion
    keywords: dict[str, float]  # rule-tagger evidence: phrase -> weight (title hits x1.5)
    specific: bool = False  # festival-style occasion a product can be *exclusively* tied to


